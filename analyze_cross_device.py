#!/usr/bin/env python3
"""
Cross-Device Wi-Fi Localization & Calibration Analysis Script
============================================================
Analyzes `localization_feedback.csv` generated by the mobile app to quantify:
  1. Same-Device Baseline (Oppo -> Oppo): k-NN vs Fuzzy vs Pattern
  2. Cross-Device Uncalibrated (Oppo Map -> Samsung): k-NN vs Fuzzy vs Pattern
  3. Cross-Device Calibrated (Oppo Map -> Samsung + Offset): k-NN vs Fuzzy vs Pattern

Generates a comparative performance table and bar chart visualization.
"""

import os
import sys
import csv
import numpy as np

OUTPUT_DIR = "distribution_plots"


def parse_feedback_csv(filepath):
    records = []
    with open(filepath, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = None
        for row in reader:
            if not row or not row[0].strip():
                continue
            if row[0].strip().startswith("timestamp"):
                header = [h.strip() for h in row]
                continue
            if len(row) < 9:
                continue

            try:
                rec = {
                    "timestamp_ms": int(row[0].strip()) if row[0].strip().isdigit() else 0,
                    "iso_time": row[1].strip(),
                    "actual_spot": row[2].strip(),
                    "knn_predicted": row[3].strip(),
                    "knn_correct": row[4].strip() in ("1", "true", "True"),
                    "knn_margin": float(row[5].strip()) if row[5].strip() else 0.0,
                    "fuzzy_predicted": row[6].strip(),
                    "fuzzy_correct": row[7].strip() in ("1", "true", "True"),
                    "fuzzy_margin": float(row[8].strip()) if row[8].strip() else 0.0,
                    "query_signals": row[9].strip() if len(row) > 9 else "",
                    "pattern_predicted": row[10].strip() if len(row) > 10 else "",
                    "pattern_correct": row[11].strip() in ("1", "true", "True") if len(row) > 11 else False,
                    "pattern_margin": float(row[12].strip()) if len(row) > 12 and row[12].strip() else 0.0,
                    "map_source": row[13].strip() if len(row) > 13 and row[13].strip() else "LOCAL",
                    "ref_device": row[14].strip() if len(row) > 14 else "",
                    "locate_device": row[15].strip() if len(row) > 15 else "",
                    "calib_offset_db": float(row[16].strip()) if len(row) > 16 and row[16].strip() else None,
                }
                records.append(rec)
            except Exception as e:
                # Skip malformed lines
                continue
    return records


def categorize_records(records):
    groups = {
        "Same-Device (Local)": [],
        "Cross-Device (Uncalibrated)": [],
        "Cross-Device (Calibrated)": []
    }

    for r in records:
        source = r["map_source"].upper()
        offset = r["calib_offset_db"]

        if source == "LOCAL":
            groups["Same-Device (Local)"].append(r)
        elif source == "IMPORTED":
            if offset is not None:
                groups["Cross-Device (Calibrated)"].append(r)
            else:
                groups["Cross-Device (Uncalibrated)"].append(r)
        else:
            groups["Same-Device (Local)"].append(r)

    return groups


def compute_metrics(recs):
    n = len(recs)
    if n == 0:
        return None

    knn_acc = sum(1 for r in recs if r["knn_correct"]) / n * 100.0
    fuzzy_acc = sum(1 for r in recs if r["fuzzy_correct"]) / n * 100.0

    # Pattern results may only exist in rows tested with pattern strategy
    has_pattern = [r for r in recs if r["pattern_predicted"]]
    n_pat = len(has_pattern)
    pat_acc = (sum(1 for r in has_pattern if r["pattern_correct"]) / n_pat * 100.0) if n_pat > 0 else 0.0

    offsets = [r["calib_offset_db"] for r in recs if r["calib_offset_db"] is not None]
    avg_offset = np.mean(offsets) if offsets else None

    return {
        "count": n,
        "knn_acc": knn_acc,
        "fuzzy_acc": fuzzy_acc,
        "pat_acc": pat_acc,
        "pat_count": n_pat,
        "avg_offset": avg_offset
    }


def print_summary_table(groups):
    print("\n" + "=" * 84)
    print(" 📊 CROSS-DEVICE WI-FI LOCALIZATION BENCHMARK SUMMARY")
    print("=" * 84)
    header = f"{'Configuration':<30} | {'N':>5} | {'k-NN Acc':>10} | {'Fuzzy Acc':>11} | {'Pattern Acc':>12} | {'Offset':>8}"
    print(header)
    print("-" * 84)

    markdown_rows = []
    plot_data = {}

    for name, recs in groups.items():
        m = compute_metrics(recs)
        if m is None:
            print(f"{name:<30} | {0:>5} | {'N/A':>10} | {'N/A':>11} | {'N/A':>12} | {'N/A':>8}")
            continue

        off_str = f"{m['avg_offset']:+.1f} dB" if m["avg_offset"] is not None else "0 dB"
        pat_str = f"{m['pat_acc']:.1f}%" if m["pat_count"] > 0 else "N/A"
        row_str = f"{name:<30} | {m['count']:>5} | {m['knn_acc']:>9.1f}% | {m['fuzzy_acc']:>10.1f}% | {pat_str:>12} | {off_str:>8}"
        print(row_str)

        markdown_rows.append(
            f"| {name} | {m['count']} | {m['knn_acc']:.1f}% | {m['fuzzy_acc']:.1f}% | {pat_str} | {off_str} |"
        )
        plot_data[name] = m

    print("=" * 84 + "\n")

    print("📝 Markdown Table for Academic Report / Proposals:")
    print("| Configuration | N | k-NN Acc | Fuzzy Matrix Acc | Pattern Acc | Antenna Offset |")
    print("|:---|:---:|:---:|:---:|:---:|:---:|")
    for row in markdown_rows:
        print(row)
    print()

    return plot_data


def plot_comparison(plot_data):
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("ℹ️ matplotlib not installed; skipping plot generation.")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    categories = [cat for cat, m in plot_data.items() if m is not None]
    if not categories:
        return

    x = np.arange(len(categories))
    width = 0.25

    knn_vals = [plot_data[c]["knn_acc"] for c in categories]
    fuzzy_vals = [plot_data[c]["fuzzy_acc"] for c in categories]
    pat_vals = [plot_data[c]["pat_acc"] for c in categories]

    fig, ax = plt.subplots(figsize=(10, 6))

    rects1 = ax.bar(x - width, knn_vals, width, label="Strategy 1: Centroid k-NN", color="#1976D2")
    rects2 = ax.bar(x, fuzzy_vals, width, label="Strategy 2: Fuzzy 3D Matrix", color="#388E3C")
    rects3 = ax.bar(x + width, pat_vals, width, label="Strategy 3: Cross-Device Pattern", color="#E65100")

    ax.set_ylabel("Classification Accuracy (%)", fontsize=12, fontweight="bold")
    ax.set_title("Wi-Fi Fingerprint Accuracy Across Heterogeneous Devices", fontsize=14, fontweight="bold", pad=15)
    ax.set_xticks(x)
    ax.set_xticklabels(categories, fontsize=11, fontweight="bold")
    ax.set_ylim(0, 105)
    ax.axhline(80, color="gray", linestyle="--", alpha=0.6, label="80% Baseline Target")
    ax.grid(axis="y", linestyle=":", alpha=0.7)
    ax.legend(loc="lower right", framealpha=0.9)

    def autolabel(rects):
        for rect in rects:
            height = rect.get_height()
            if height > 0:
                ax.annotate(f"{height:.1f}%",
                            xy=(rect.get_x() + rect.get_width() / 2, height),
                            xytext=(0, 3),
                            textcoords="offset points",
                            ha="center", va="bottom", fontsize=10, fontweight="bold")

    autolabel(rects1)
    autolabel(rects2)
    autolabel(rects3)

    plt.tight_layout()
    out_path = os.path.join(OUTPUT_DIR, "cross_device_comparison.png")
    plt.savefig(out_path, dpi=300)
    plt.close()
    print(f"📈 Saved comparative plot to '{out_path}'\n")


def main():
    filepath = sys.argv[1] if len(sys.argv) > 1 else "localization_feedback.csv"
    if not os.path.exists(filepath):
        print(f"❌ Feedback CSV '{filepath}' not found.")
        print("💡 Usage:")
        print("   1. Pull the CSV from device: adb exec-out run-as com.example.wififingerprint cat files/localization_feedback.csv > localization_feedback.csv")
        print("   2. Run: python analyze_cross_device.py localization_feedback.csv")
        return

    records = parse_feedback_csv(filepath)
    print(f"📂 Loaded {len(records)} evaluation records from '{filepath}'.")
    groups = categorize_records(records)
    plot_data = print_summary_table(groups)
    plot_comparison(plot_data)


if __name__ == "__main__":
    main()
