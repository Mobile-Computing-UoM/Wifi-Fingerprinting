#!/usr/bin/env python3
"""
Wi-Fi Positioning Experiment Analysis & Statistical Suite
=========================================================
Analyzes `experiment_results.csv` generated by the Android Experiment Runner
to quantify localization accuracy and physical metric error across different
Reference Point (RP) separations (e.g. 2m, 3m, 4m, 5m, 10m).

Evaluates:
  1. Spot Classification Accuracy (%) for k-NN and Fuzzy Matrix
  2. Physical Localization Distance Error (Mean, Median, 75th/90th percentile, Max, Std Dev)
  3. Cumulative Distribution Function (CDF) of Metric Distance Error
  4. Per-Spot Error Spatial Heatmap / Breakdown (S1 - S8)
  5. k-NN vs. Fuzzy Matrix Algorithm Agreement & Divergence

Generates publication-quality plots in `experiment_plots/` and prints a Markdown report.

Usage:
  python analyze_experiment.py [path_to_experiment_results.csv]
  python analyze_experiment.py --generate-mock   # Generates sample data for testing
"""

import os
import sys
import csv
import math
import argparse
from collections import defaultdict

try:
    import numpy as np
    HAS_NUMPY = True
except ImportError:
    HAS_NUMPY = False

try:
    import matplotlib.pyplot as plt
    HAS_MATPLOTLIB = True
except ImportError:
    HAS_MATPLOTLIB = False

OUTPUT_DIR = "experiment_plots"


def parse_experiment_csv(filepath):
    """
    Parses experiment_results.csv safely handling quoted fields.
    """
    records = []
    if not os.path.exists(filepath):
        return records

    with open(filepath, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = None
        for row in reader:
            if not row or not row[0].strip():
                continue
            first_col = row[0].strip()
            if first_col.startswith("timestamp"):
                header = [h.strip() for h in row]
                continue
            if len(row) < 18:
                continue

            try:
                rec = {
                    "timestamp_ms": int(first_col) if first_col.isdigit() else 0,
                    "iso_time": row[1].strip(),
                    "separation_m": float(row[2].strip()),
                    "trial_idx": int(row[3].strip()),
                    "total_trials": int(row[4].strip()),
                    "locate_n": int(row[5].strip()),
                    "actual_spot": row[6].strip(),
                    "actual_x": float(row[7].strip()),
                    "actual_y": float(row[8].strip()),
                    "knn_pred_spot": row[9].strip(),
                    "knn_pred_x": float(row[10].strip()),
                    "knn_pred_y": float(row[11].strip()),
                    "knn_error_m": float(row[12].strip()),
                    "knn_correct": row[13].strip() in ("1", "true", "True"),
                    "fuzzy_pred_spot": row[14].strip(),
                    "fuzzy_pred_x": float(row[15].strip()),
                    "fuzzy_pred_y": float(row[16].strip()),
                    "fuzzy_error_m": float(row[17].strip()),
                    "fuzzy_correct": row[18].strip() in ("1", "true", "True"),
                    "raw_signals": row[19].strip() if len(row) > 19 else ""
                }
                records.append(rec)
            except (ValueError, IndexError):
                continue

    return records


def compute_statistics(values):
    """Computes mean, std, median, p75, p90, min, max without hard numpy dependency."""
    if not values:
        return {"count": 0, "mean": 0.0, "std": 0.0, "median": 0.0, "p75": 0.0, "p90": 0.0, "min": 0.0, "max": 0.0}

    s = sorted(values)
    n = len(s)
    mean = sum(s) / n
    variance = sum((x - mean) ** 2 for x in s) / n if n > 0 else 0.0
    std = math.sqrt(variance)

    def percentile(p):
        k = (n - 1) * p
        f = math.floor(k)
        c = math.ceil(k)
        if f == c:
            return s[int(k)]
        d0 = s[int(f)] * (c - k)
        d1 = s[int(c)] * (k - f)
        return d0 + d1

    median = percentile(0.50)
    p75 = percentile(0.75)
    p90 = percentile(0.90)

    return {
        "count": n,
        "mean": mean,
        "std": std,
        "median": median,
        "p75": p75,
        "p90": p90,
        "min": s[0],
        "max": s[-1]
    }


def analyze_records(records):
    """Aggregates metrics by separation and spot."""
    by_separation = defaultdict(list)
    for r in records:
        by_separation[r["separation_m"]].append(r)

    results = {}
    for sep, group in sorted(by_separation.items()):
        total = len(group)
        knn_correct = sum(1 for r in group if r["knn_correct"])
        fuzzy_correct = sum(1 for r in group if r["fuzzy_correct"])
        both_agree = sum(1 for r in group if r["knn_pred_spot"] == r["fuzzy_pred_spot"])

        knn_errors = [r["knn_error_m"] for r in group]
        fuzzy_errors = [r["fuzzy_error_m"] for r in group]

        knn_stats = compute_statistics(knn_errors)
        fuzzy_stats = compute_statistics(fuzzy_errors)

        # Breakdown by spot
        by_spot = defaultdict(list)
        for r in group:
            by_spot[r["actual_spot"]].append(r)

        spot_breakdown = {}
        for spot, s_group in sorted(by_spot.items()):
            s_knn_err = [r["knn_error_m"] for r in s_group]
            s_fuzzy_err = [r["fuzzy_error_m"] for r in s_group]
            spot_breakdown[spot] = {
                "count": len(s_group),
                "knn_acc": (sum(1 for r in s_group if r["knn_correct"]) / len(s_group)) * 100.0,
                "knn_mean_err": sum(s_knn_err) / len(s_knn_err) if s_knn_err else 0.0,
                "fuzzy_acc": (sum(1 for r in s_group if r["fuzzy_correct"]) / len(s_group)) * 100.0,
                "fuzzy_mean_err": sum(s_fuzzy_err) / len(s_fuzzy_err) if s_fuzzy_err else 0.0,
            }

        results[sep] = {
            "total_trials": total,
            "knn_acc_pct": (knn_correct / total) * 100.0 if total > 0 else 0.0,
            "fuzzy_acc_pct": (fuzzy_correct / total) * 100.0 if total > 0 else 0.0,
            "agreement_pct": (both_agree / total) * 100.0 if total > 0 else 0.0,
            "knn_stats": knn_stats,
            "fuzzy_stats": fuzzy_stats,
            "spot_breakdown": spot_breakdown,
            "raw_group": group
        }

    return results


def print_markdown_report(analysis):
    """Outputs a rich Markdown summary report."""
    print("\n" + "=" * 80)
    print("📊 WI-FI POSITIONING EXPERIMENT ANALYSIS REPORT")
    print("=" * 80 + "\n")

    print("### 1. Overall Performance Across Point Separations\n")
    print("| Separation | Trials | k-NN Acc (%) | k-NN Mean Err (m) | k-NN Median (m) | Fuzzy Acc (%) | Fuzzy Mean Err (m) | Fuzzy Median (m) | Agreement (%) |")
    print("| :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |")

    for sep, data in sorted(analysis.items()):
        ks = data["knn_stats"]
        fs = data["fuzzy_stats"]
        print(f"| **{sep:.1f} m** | {data['total_trials']} | "
              f"**{data['knn_acc_pct']:.1f}%** | {ks['mean']:.2f} ± {ks['std']:.2f} | {ks['median']:.2f} | "
              f"**{data['fuzzy_acc_pct']:.1f}%** | {fs['mean']:.2f} ± {fs['std']:.2f} | {fs['median']:.2f} | "
              f"{data['agreement_pct']:.1f}% |")

    print("\n### 2. Per-Spot Accuracy & Metric Error Breakdown\n")
    for sep, data in sorted(analysis.items()):
        print(f"#### Separation: **{sep:.1f} metres** ({data['total_trials']} total trials)")
        print("| Spot | Trials | k-NN Acc (%) | k-NN Mean Err (m) | Fuzzy Acc (%) | Fuzzy Mean Err (m) |")
        print("| :--- | :---: | :---: | :---: | :---: | :---: |")
        for spot, sb in data["spot_breakdown"].items():
            print(f"| `{spot}` | {sb['count']} | {sb['knn_acc']:.1f}% | {sb['knn_mean_err']:.2f}m | {sb['fuzzy_acc']:.1f}% | {sb['fuzzy_mean_err']:.2f}m |")
        print()


def generate_plots(analysis):
    """Generates all 4 scientific comparison figures."""
    if not HAS_MATPLOTLIB:
        print("⚠️ matplotlib not installed; skipping plot generation. (Run 'pip install matplotlib' to enable)")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    separations = sorted(analysis.keys())
    if not separations:
        return

    sep_labels = [f"{s:.1f}m" for s in separations]
    knn_accs = [analysis[s]["knn_acc_pct"] for s in separations]
    fuzzy_accs = [analysis[s]["fuzzy_acc_pct"] for s in separations]

    knn_mean_errs = [analysis[s]["knn_stats"]["mean"] for s in separations]
    knn_std_errs = [analysis[s]["knn_stats"]["std"] for s in separations]
    fuzzy_mean_errs = [analysis[s]["fuzzy_stats"]["mean"] for s in separations]
    fuzzy_std_errs = [analysis[s]["fuzzy_stats"]["std"] for s in separations]

    knn_median_errs = [analysis[s]["knn_stats"]["median"] for s in separations]
    fuzzy_median_errs = [analysis[s]["fuzzy_stats"]["median"] for s in separations]

    # -------------------------------------------------------------
    # Plot 1: Classification Accuracy vs Separation (Clustered Bar)
    # -------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    x = np.arange(len(separations)) if HAS_NUMPY else list(range(len(separations)))
    width = 0.35

    if HAS_NUMPY:
        plt.bar(x - width / 2, knn_accs, width, label='k-NN Strategy', color='#1976D2', edgecolor='black', alpha=0.85)
        plt.bar(x + width / 2, fuzzy_accs, width, label='Fuzzy Matrix Strategy', color='#388E3C', edgecolor='black', alpha=0.85)
        plt.xticks(x, sep_labels, fontsize=11)
    else:
        plt.bar(sep_labels, knn_accs, label='k-NN Strategy', color='#1976D2', alpha=0.85)

    plt.xlabel('Reference Point (RP) Separation', fontsize=12, fontweight='bold')
    plt.ylabel('Spot Classification Accuracy (%)', fontsize=12, fontweight='bold')
    plt.title('Indoor Localization Spot Accuracy vs. Grid Separation', fontsize=13, fontweight='bold')
    plt.ylim(0, 105)
    plt.grid(axis='y', linestyle='--', alpha=0.5)
    plt.legend(frameon=True, fontsize=11)
    plt.tight_layout()
    p1 = os.path.join(OUTPUT_DIR, "1_accuracy_vs_separation.png")
    plt.savefig(p1, dpi=300)
    plt.close()
    print(f"📈 Saved Accuracy comparison plot: {p1}")

    # -------------------------------------------------------------
    # Plot 2: Metric Distance Error vs Separation (Mean & Std Dev)
    # -------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    if HAS_NUMPY:
        plt.errorbar(x, knn_mean_errs, yerr=knn_std_errs, fmt='-o', color='#1976D2', label='k-NN Mean ± 1σ',
                     capsize=5, capthick=1.5, linewidth=2, markersize=7)
        plt.plot(x, knn_median_errs, '--s', color='#0D47A1', label='k-NN Median', linewidth=1.5, markersize=6)

        plt.errorbar(x, fuzzy_mean_errs, yerr=fuzzy_std_errs, fmt='-^', color='#388E3C', label='Fuzzy Matrix Mean ± 1σ',
                     capsize=5, capthick=1.5, linewidth=2, markersize=7)
        plt.plot(x, fuzzy_median_errs, '--d', color='#1B5E20', label='Fuzzy Median', linewidth=1.5, markersize=6)
        plt.xticks(x, sep_labels, fontsize=11)
    else:
        plt.plot(sep_labels, knn_mean_errs, '-o', label='k-NN Mean Error (m)')
        plt.plot(sep_labels, fuzzy_mean_errs, '-^', label='Fuzzy Matrix Mean Error (m)')

    plt.xlabel('Reference Point (RP) Separation', fontsize=12, fontweight='bold')
    plt.ylabel('Metric Distance Error (metres)', fontsize=12, fontweight='bold')
    plt.title('Physical Localization Distance Error vs. Grid Separation', fontsize=13, fontweight='bold')
    plt.grid(True, linestyle='--', alpha=0.5)
    plt.legend(frameon=True, fontsize=10)
    plt.tight_layout()
    p2 = os.path.join(OUTPUT_DIR, "2_distance_error_vs_separation.png")
    plt.savefig(p2, dpi=300)
    plt.close()
    print(f"📈 Saved Distance Error comparison plot: {p2}")

    # -------------------------------------------------------------
    # Plot 3: Cumulative Distribution Function (CDF) of Error
    # -------------------------------------------------------------
    plt.figure(figsize=(9, 6))
    colors = ['#1976D2', '#D32F2F', '#388E3C', '#F57C00', '#7B1FA2']

    for idx, sep in enumerate(separations):
        group = analysis[sep]["raw_group"]
        color = colors[idx % len(colors)]

        # k-NN CDF
        knn_err = sorted([r["knn_error_m"] for r in group])
        if knn_err:
            y_knn = [i / len(knn_err) for i in range(1, len(knn_err) + 1)]
            plt.step(knn_err, y_knn, label=f'{sep:.1f}m - k-NN', color=color, linewidth=2)

        # Fuzzy CDF
        fuzzy_err = sorted([r["fuzzy_error_m"] for r in group])
        if fuzzy_err:
            y_fuzzy = [i / len(fuzzy_err) for i in range(1, len(fuzzy_err) + 1)]
            plt.step(fuzzy_err, y_fuzzy, label=f'{sep:.1f}m - Fuzzy', color=color, linestyle='--', linewidth=1.8)

    plt.xlabel('Localization Distance Error (metres)', fontsize=12, fontweight='bold')
    plt.ylabel('Cumulative Probability P(Error ≤ d)', fontsize=12, fontweight='bold')
    plt.title('Cumulative Distribution Function (CDF) of Distance Error', fontsize=13, fontweight='bold')
    plt.axhline(0.50, color='gray', linestyle=':', label='50th percentile (Median)')
    plt.axhline(0.90, color='lightgray', linestyle=':', label='90th percentile')
    plt.xlim(0, max(separations) * 1.5 if separations else 10)
    plt.ylim(0, 1.05)
    plt.grid(True, linestyle='--', alpha=0.5)
    plt.legend(frameon=True, fontsize=9, loc='lower right')
    plt.tight_layout()
    p3 = os.path.join(OUTPUT_DIR, "3_cdf_distance_error.png")
    plt.savefig(p3, dpi=300)
    plt.close()
    print(f"📈 Saved CDF Error Distribution plot: {p3}")

    # -------------------------------------------------------------
    # Plot 4: Per-Spot Mean Error Breakdown across Separations
    # -------------------------------------------------------------
    all_spots = sorted(list(set(r["actual_spot"] for s in separations for r in analysis[s]["raw_group"])))
    if all_spots and HAS_NUMPY:
        plt.figure(figsize=(10, 5))
        spot_idx = np.arange(len(all_spots))
        total_bars = len(separations)
        bar_w = 0.8 / total_bars

        for i, sep in enumerate(separations):
            sb = analysis[sep]["spot_breakdown"]
            errs = [sb.get(s, {}).get("knn_mean_err", 0.0) for s in all_spots]
            offset = (i - (total_bars - 1) / 2) * bar_w
            plt.bar(spot_idx + offset, errs, bar_w, label=f'k-NN @ {sep:.1f}m', alpha=0.85)

        plt.xticks(spot_idx, all_spots, fontsize=11)
        plt.xlabel('Physical Reference Spot', fontsize=12, fontweight='bold')
        plt.ylabel('Mean Distance Error (metres)', fontsize=12, fontweight='bold')
        plt.title('Mean Distance Error by Physical Spot across Separations', fontsize=13, fontweight='bold')
        plt.grid(axis='y', linestyle='--', alpha=0.5)
        plt.legend(frameon=True, fontsize=10)
        plt.tight_layout()
        p4 = os.path.join(OUTPUT_DIR, "4_per_spot_error_breakdown.png")
        plt.savefig(p4, dpi=300)
        plt.close()
        print(f"📈 Saved Per-Spot Error breakdown plot: {p4}")

    print(f"\n✅ All plots generated successfully in directory: '{OUTPUT_DIR}/'\n")


def generate_mock_csv(filepath="experiment_results.csv"):
    """
    Generates synthetic experiment results simulating 2m, 3m, 4m, 5m separations
    with 20 iterations across spots S1-S8, realistic noise, and distance errors.
    """
    import random
    separations = [2.0, 3.0, 4.0, 5.0]
    spots = [f"S{i}" for i in range(1, 9)]
    trials_per_spot = 20
    locate_n = 10

    records = []
    base_ts = 1730000000000

    print(f"🧪 Generating synthetic multi-separation experiment data: {filepath}")

    with open(filepath, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "timestamp_ms", "iso_time", "separation_m", "trial_idx", "total_trials", "locate_n",
            "actual_spot", "actual_x", "actual_y",
            "knn_pred_spot", "knn_pred_x", "knn_pred_y", "knn_error_m", "knn_correct",
            "fuzzy_pred_spot", "fuzzy_pred_x", "fuzzy_pred_y", "fuzzy_error_m", "fuzzy_correct",
            "raw_signals"
        ])

        for sep in separations:
            # Layout coordinates: S1 at 0m, S2 at sep*1, S3 at sep*2 ...
            coords = {f"S{i+1}": (i * sep, 0.0) for i in range(8)}

            for s_idx, spot in enumerate(spots):
                actual_x, actual_y = coords[spot]

                for t in range(1, trials_per_spot + 1):
                    ts = base_ts + int(sep * 100000) + s_idx * 5000 + t * 1200
                    iso = "2026-11-06T12:00:00Z"

                    # Realistic error behavior:
                    # Small separation (2m): 90% accuracy, mean error ~0.3m
                    # Medium separation (4m): 75% accuracy, mean error ~0.9m
                    # Large separation (5m): 65% accuracy, mean error ~1.5m
                    acc_prob = max(0.40, 0.95 - (sep - 2.0) * 0.10)

                    # k-NN prediction
                    if random.random() < acc_prob:
                        knn_spot = spot
                        knn_x = actual_x + random.gauss(0, 0.25 * (sep / 2.0))
                        knn_y = actual_y + random.gauss(0, 0.25 * (sep / 2.0))
                    else:
                        # Neighboring spot error
                        offset = random.choice([-1, 1])
                        neighbor_idx = max(0, min(7, s_idx + offset))
                        knn_spot = spots[neighbor_idx]
                        knn_x = coords[knn_spot][0] + random.gauss(0, 0.3)
                        knn_y = coords[knn_spot][1] + random.gauss(0, 0.3)

                    dx_knn = actual_x - knn_x
                    dy_knn = actual_y - knn_y
                    knn_err = math.sqrt(dx_knn * dx_knn + dy_knn * dy_knn)
                    knn_corr = 1 if knn_spot == spot else 0

                    # Fuzzy prediction (often slightly more resilient at boundary)
                    fuzzy_acc_prob = max(0.45, acc_prob + random.uniform(-0.05, 0.08))
                    if random.random() < fuzzy_acc_prob:
                        fuzzy_spot = spot
                        fuzzy_x = actual_x + random.gauss(0, 0.20 * (sep / 2.0))
                        fuzzy_y = actual_y + random.gauss(0, 0.20 * (sep / 2.0))
                    else:
                        offset = random.choice([-1, 1])
                        neighbor_idx = max(0, min(7, s_idx + offset))
                        fuzzy_spot = spots[neighbor_idx]
                        fuzzy_x = coords[fuzzy_spot][0] + random.gauss(0, 0.3)
                        fuzzy_y = coords[fuzzy_spot][1] + random.gauss(0, 0.3)

                    dx_f = actual_x - fuzzy_x
                    dy_f = actual_y - fuzzy_y
                    fuzzy_err = math.sqrt(dx_f * dx_f + dy_f * dy_f)
                    fuzzy_corr = 1 if fuzzy_spot == spot else 0

                    signals = f"anon_ap1={int(-50 - s_idx*3 + random.gauss(0, 2))};anon_ap2={int(-70 + s_idx*2 + random.gauss(0, 2))}"

                    writer.writerow([
                        ts, iso, f"{sep:.2f}", t, trials_per_spot, locate_n,
                        spot, f"{actual_x:.2f}", f"{actual_y:.2f}",
                        knn_spot, f"{knn_x:.2f}", f"{knn_y:.2f}", f"{knn_err:.3f}", knn_corr,
                        fuzzy_spot, f"{fuzzy_x:.2f}", f"{fuzzy_y:.2f}", f"{fuzzy_err:.3f}", fuzzy_corr,
                        signals
                    ])

    print(f"✅ Generated synthetic dataset with {len(separations) * len(spots) * trials_per_spot} records in '{filepath}'\n")


def main():
    parser = argparse.ArgumentParser(description="Wi-Fi Positioning Experiment Analysis & Statistical Suite")
    parser.add_argument("csv_file", nargs="?", default="experiment_results.csv",
                        help="Path to experiment_results.csv (default: experiment_results.csv)")
    parser.add_argument("--generate-mock", action="store_true",
                        help="Generate synthetic experiment_results.csv for testing and visualization")
    args = parser.parse_args()

    if args.generate_mock:
        generate_mock_csv(args.csv_file)

    if not os.path.exists(args.csv_file):
        print(f"❌ Error: File '{args.csv_file}' not found.")
        print(f"💡 Run with '--generate-mock' to create test data, or pull from device using adb:")
        print(f"   adb pull /storage/emulated/0/Android/data/com.example.wififingerprint/files/{args.csv_file} .")
        return

    records = parse_experiment_csv(args.csv_file)
    if not records:
        print(f"⚠️ No valid experiment records found in '{args.csv_file}'.")
        return

    print(f"📂 Loaded {len(records)} experiment trial records from '{args.csv_file}'")
    analysis = analyze_records(records)
    print_markdown_report(analysis)
    generate_plots(analysis)


if __name__ == "__main__":
    main()

